import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {chromium} from 'playwright';
import {createServer} from 'vite';

async function main() {
  const server = await createServer({configFile: resolve('.devin/motion-canvas.vite.ts'), server: {host: '127.0.0.1', port: 9002, strictPort: false}});
  await server.listen();
  const browser = await chromium.launch({headless: true, ...(process.env.CHROME_PATH ? {executablePath: process.env.CHROME_PATH} : {channel: 'chrome'})});
  try {
    const context = await browser.newContext({viewport: {width: 1512, height: 1100}});
    const page = await context.newPage();
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    const url = `${server.resolvedUrls!.local[0]}motion-canvas/workbench.html`;
    await page.goto(url, {waitUntil: 'networkidle'});
    await page.waitForFunction(() => document.getElementById('player-status')?.textContent?.includes('实时场景'));
    await page.waitForFunction(() => {
      const canvas = document.querySelector<HTMLCanvasElement>('#canvas-host canvas');
      const pixel = canvas?.getContext('2d')?.getImageData(200, 355, 1, 1).data;
      return pixel && pixel[0] >= 248 && pixel[1] >= 248 && pixel[2] >= 240;
    });
    await page.screenshot({path: 'motion-canvas/workbench-desktop.png', fullPage: true});
    const speed = page.getByRole('combobox', {name: '播放倍速'});
    assert.equal(await speed.inputValue(), '1');
    await speed.selectOption('2');
    await page.waitForFunction(() => document.getElementById('player-status')?.textContent?.includes('2×'));
    await page.getByRole('button', {name: '播放动画', exact: true}).click();
    await page.waitForTimeout(650);
    await page.getByRole('button', {name: '暂停动画', exact: true}).click();
    const fastFrames = Number(await page.locator('#timeline').inputValue()) - 60;
    await page.getByRole('button', {name: '建立直觉', exact: true}).click();
    await page.waitForFunction(() => Number((document.getElementById('timeline') as HTMLInputElement).value) === 60);
    await speed.selectOption('0.5');
    await page.waitForFunction(() => document.getElementById('player-status')?.textContent?.includes('0.5×'));
    await page.getByRole('button', {name: '播放动画', exact: true}).click();
    await page.waitForTimeout(650);
    await page.getByRole('button', {name: '暂停动画', exact: true}).click();
    const slowFrames = Number(await page.locator('#timeline').inputValue()) - 60;
    assert.ok(slowFrames > 0 && fastFrames > slowFrames * 1.4, `Playback did not speed up: ${fastFrames} vs ${slowFrames} frames`);
    await speed.selectOption('1');
    await page.waitForFunction(() => document.getElementById('player-status')?.textContent?.includes('1×'));
    await page.locator('#timeline').evaluate((input: HTMLInputElement) => {input.value = '3740'; input.dispatchEvent(new Event('input', {bubbles: true}));});
    await page.waitForFunction(() => document.getElementById('state-window')?.textContent === '[4, 6] · k = 3');
    assert.match(await page.locator('#focus-body').innerText(), /\[4, 6\].*\[5, 7\]/);
    await page.screenshot({path: 'motion-canvas/window-entering.png'});
    await page.locator('#timeline').evaluate((input: HTMLInputElement) => {input.value = '3795'; input.dispatchEvent(new Event('input', {bubbles: true}));});
    await page.waitForFunction(() => document.getElementById('state-window')?.textContent === '[5, 7] · k = 3');
    assert.match(await page.locator('#focus-body').innerText(), /当前范围 \[5, 7\]/);
    await page.screenshot({path: 'motion-canvas/window-settled.png'});
    await page.getByRole('button', {name: '建立直觉', exact: true}).click();
    await page.waitForFunction(() => Number((document.getElementById('timeline') as HTMLInputElement).value) === 60);
    await page.getByRole('button', {name: '播放动画', exact: true}).click();
    await page.waitForFunction(() => Number((document.getElementById('timeline') as HTMLInputElement).value) > 75);
    await page.getByRole('button', {name: '暂停动画', exact: true}).click();
    await page.getByRole('button', {name: '复杂度', exact: true}).click();
    await page.waitForFunction(() => document.getElementById('state-result')?.textContent === '[3, 3, 5, 5, 6, 7]');
    await page.getByLabel('数组 nums').fill('1,,2');
    await page.getByRole('button', {name: '更新演示'}).click();
    assert.equal(await page.locator('#input-error').isVisible(), true);
    assert.equal(await page.locator('#nums').inputValue(), '1,,2');
    await page.getByRole('button', {name: '递减序列', exact: true}).click();
    await page.waitForFunction(() => !(document.getElementById('apply-input') as HTMLButtonElement).disabled);
    await page.getByRole('button', {name: '复杂度', exact: true}).click();
    await page.waitForFunction(() => document.getElementById('state-result')?.textContent === '[9, 8, 7, 6]');
    await page.screenshot({path: 'motion-canvas/workbench-variant.png', fullPage: true});
    await page.getByRole('tab', {name: '参考代码'}).click();
    await page.getByLabel('参考语言').selectOption('python');
    assert.match(await page.locator('#code-content').innerText(), /collections import deque/);
    await page.getByLabel('参考语言').selectOption('cpp');
    assert.match(await page.locator('#code-content').innerText(), /std::deque/);
    await page.getByRole('tab', {name: '参考代码'}).focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#tab-practice').getAttribute('aria-selected'), 'true');
    await page.getByLabel('保留 0，因为 8 比新元素 6 大').check();
    await page.getByRole('button', {name: '提交判断'}).click();
    assert.equal(await page.locator('#answer-feedback').getAttribute('data-correct'), 'false');
    assert.match(await page.locator('#attempt-summary').innerText(), /首次待纠正/);
    await page.getByRole('button', {name: '下一题'}).click();
    await page.getByRole('button', {name: '给我一点提示'}).click();
    await page.getByLabel('答案仍正确，只是不再保证值严格递减').check();
    await page.getByRole('button', {name: '提交判断'}).click();
    assert.match(await page.locator('#attempt-summary').innerText(), /首次借助提示/);
    await speed.selectOption('1.5');
    await page.waitForFunction(() => document.getElementById('player-status')?.textContent?.includes('1.5×'));
    await page.reload({waitUntil: 'networkidle'});
    await page.waitForFunction(() => document.getElementById('player-status')?.textContent?.includes('实时场景'));
    assert.equal(await speed.inputValue(), '1.5');
    assert.equal(await page.locator('#nums').inputValue(), '9, 8, 7, 6, 5, 4');
    await page.getByRole('tab', {name: /迁移自测/}).click();
    assert.match(await page.locator('#attempt-summary').innerText(), /首次待纠正/);
    assert.match(await page.locator('#attempt-summary').innerText(), /首次借助提示/);
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({path: 'motion-canvas/workbench-practice.png', fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    await page.reload({waitUntil: 'networkidle'});
    await page.waitForFunction(() => document.getElementById('player-status')?.textContent?.includes('实时场景'));
    assert.equal(await page.getByRole('checkbox', {name: '静态步骤'}).isChecked(), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByRole('button', {name: '复杂度', exact: true}).click();
    assert.equal(await page.locator('#state-result').innerText(), '[9, 8, 7, 6]');
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({path: 'motion-canvas/workbench-mobile.png', fullPage: true});
    await page.setViewportSize({width: 1280, height: 900});
    await page.emulateMedia({reducedMotion: 'reduce'});
    await page.reload({waitUntil: 'networkidle'});
    assert.equal(await page.getByRole('checkbox', {name: '静态步骤'}).isChecked(), true);
    await page.evaluate(() => localStorage.setItem('algorithm-studio:attempts:v1', '{broken'));
    await page.reload({waitUntil: 'networkidle'});
    await page.getByRole('tab', {name: /迁移自测/}).click();
    assert.match(await page.locator('#storage-status').innerText(), /不会覆盖/);
    await page.getByLabel('移除队头 0，因为它不在新窗口内').check();
    await page.getByRole('button', {name: '提交判断'}).click();
    assert.equal(await page.evaluate(() => localStorage.getItem('algorithm-studio:attempts:v1')), '{broken');
    assert.deepEqual(errors, []);
    console.log('PASS: playback, seeking, dynamic inputs, invalid input recovery, three language views, keyboard tabs, quiz feedback, persistent first attempts, corrupt storage preservation, mobile layout, reduced motion.');
  } finally {
    await browser.close();
    await server.close();
  }
}
main().catch(error => {console.error(error); process.exitCode = 1;});
